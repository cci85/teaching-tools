// ── 講義撰寫的角色、規則與輸出結構（[1] 使用） ──
// 要調整講義結構，只需改這個檔案。
// opts = { intro: 是否有引言節, overview: 核心節是否先寫架構總覽,
//          format: "bullets"（標題→條列→段落）| "prose"（標題→純段落）,
//          examples: "inline"（散在各概念中）| "section"（獨立一節）| "none" }

const HANDOUT_DEFAULTS = { intro: true, overview: true, format: "bullets", examples: "inline" };
const LIMITS = "「延伸閱讀與資料界限」一節";
const NUM = ["一", "二", "三", "四", "五", "六"];

// 依勾選組出章節清單（名稱、說明）
function handoutSections(opts) {
  const o = { ...HANDOUT_DEFAULTS, ...opts };
  const secs = [];
  if (o.intro) secs.push({ key: "intro", title: "為什麼要理解這個主題？", body: ["以一段情境、管理決策或研究問題引入。"] });
  secs.push({ key: "core", title: "核心概念與理論架構", body: coreBody(o) });
  if (o.examples === "section") secs.push({
    key: "apply", title: "管理與行銷應用",
    body: ["用 1–2 個明確標示的「說明性例子」，將理論連回實際行銷決策；不得將例子當成來源已證實的實證結論。"]
  });
  secs.push({
    key: "limits", title: "延伸閱讀與資料界限",
    body: ["列出本講義使用的教材章節與文獻，並明確說明尚未涵蓋、證據不足、來源定義衝突或需由教師人工確認的問題。"]
  });
  return secs.map((s, i) => ({ ...s, heading: `${NUM[i]}、${s.title}` }));
}

function coreBody(o) {
  const lines = [];
    if (o.overview) {
    lines.push("  (1) 架構總覽：以一段連續文字（不使用條列）說明本單元各概念或步驟之間的邏輯順序，指出前一環節如何構成後一環節的前提；此處只交代概念之間的關係，不定義、不展開任何概念，定義一律留到下方各自的區塊。");
  }
  const items = ["白話說明（這個概念要解決什麼問題）", "正式定義與來源", "機制，以及與前後概念的關係", "與相近概念的共同點、差異與常見誤解"];
  if (o.examples === "inline") items.push("一段明確標示為「說明性例子」的文字，把這個概念連回實際行銷決策");
  const formatLine = o.format === "bullets"
    ? "標題下先列 2–4 個條列要點（判準、理論依據、實證、限制，視內容擇用），再以段落完整論述上述內容"
    : "標題下直接以完整段落論述上述內容，不使用條列";
  lines.push(
    `  ${o.overview ? "(2) " : ""}逐一展開：${o.overview ? "總覽中的" : ""}每一個概念或步驟各自獨立成一個「### 標題」${o.overview ? "，名稱與總覽中的用語一致" : ""}；每個區塊開頭先用一句話承接上一個概念，說明兩者的關係，接著依序涵蓋：${items.map((x, i) => `(${String.fromCharCode(97 + i)}) ${x}`).join("；")}。${formatLine}。每條關係的理論依據、證據狀態與限制直接寫在所屬概念的區塊內，不要另立清單重複說明。`
  );
  if (o.examples === "inline") {
    lines.push("  說明性例子規則：每個例子只服務它所在的概念，不同概念的例子不得重複使用同一個情境；不得將例子當成來源已證實的實證結論。");
  }
  lines.push("  不要畫任何圖表，不要輸出 Mermaid、flowchart 或任何圖表程式碼。");
  return lines;
}

function handoutRules(topicRef, o, coreHeading) {
  const exampleRule = o.examples === "none"
    ? "3. 清楚區分兩種文字：教材或文獻的直接主張、跨來源的綜合解釋；本講義不加入自行設計的例子。"
    : "3. 清楚區分三種文字：教材或文獻的直接主張、跨來源的綜合解釋、為幫助學生理解而設計的「說明性例子」。";
  const formatRule = o.format === "bullets"
    ? "14. 每個重點一律採「標題 → 條列要點 → 段落文字」的格式：先以小標題（###）點出該重點，再以 2–4 個條列列出關鍵要點（如判準、理論依據、實證、限制），條列之後接續完整段落，解釋要點背後的理由、概念間的關係與應用；條列只作為重點摘要，不得取代段落論述。"
    : "14. 每個重點以小標題（###）點出後，直接以完整段落論述，不使用條列。";
  return [
    "寫作與證據規則：",
    "1. 僅使用提供資料中的理論、定義、研究結果與案例；不得編造引用、研究發現、數字或作者主張。",
    "2. 每一項重要理論主張或實證陳述，使用 APA 格式標示（作者, 年份）即可；不需要、也不可以寫出章節、頁碼或「頁碼未提供」字樣。同一段落內連續引用同一來源，可以只在段落結尾標示一次，不必每句話都重複標註。",
    exampleRule,
    "3a. 每個第一次出現的專有名詞或理論名稱，必須先用一般大學生能懂的白話說明：這個詞想解決什麼問題、為什麼會有學者提出這個概念，再接著給出正式定義；不得只把來源的學術用語換句話說一次就當作解釋完畢，也不得把多個專有名詞連續條列出來卻不逐一說明其含義。",
    "4. 用繁體中文，採正式、完整、連貫的教科書式論述。",
    "5. 不得只將教材濃縮成條列（條列之後一定要有段落論述），也避免把每個概念寫成互不相干的獨立卡片；每一節都要先界定問題，再解釋概念，再說明其關係與應用。每次引入新概念時，先用 1–2 句話說明它跟前一個概念的關係、以及它是為了解決前一個概念留下的什麼問題或限制才被提出，讓整篇讀起來是一條連貫的論述脈絡，而不是一串各自獨立的名詞解釋。",
    "5a. 依學生理解所需的概念順序安排內容，而非按照來源檔案出現順序排列。",
    "5b. 只寫學生必須掌握的必教內容；邊緣、細碎或超出字數上限所能涵蓋的內容不要寫入正文。",
    "6. 對相似概念，必須說明其共同點、差異、適用範圍與常見誤解；不得將不同作者或不同理論中的相近概念直接視為同義概念。",
    "7. 若涉及實證研究，說明研究問題、設計、主要變數、結果、可作出的推論，以及限制。",
    `8. 若資料不足、定義衝突或來源間互相矛盾，於文中標示「資料界限」或「學術爭議」，不可自行統一或補足，並彙整列入${LIMITS}。`,
    "9. 不抄錄長段落教材原文；應以自己的話重述，只有關鍵定義才可短引並標示來源。",
    "10. 面向學生，不要出現「教師可提問」「學生應回答」等教師教案語言。",
    "11. 本講義不使用表格。",
    "12. 用詞一律使用「變數」，不得使用「變項」（包括自變數、依變數、中介變數、調節變數等所有複合詞）。",
    "13. 撰寫完成前，請自行檢查全文：若不同章節重複說明相同的概念、判準、程序或例子，應整合在同一處完整說明，其餘位置只以一句話承接或指回，不得重複論述。",
    formatRule,
    `15. 全文長度不得超過上方「講義總字數上限」。請自行依各節重要性分配篇幅，「${coreHeading}」應占絕大部分篇幅；寧可精簡其他各節，也必須完整寫到${LIMITS}，不得因篇幅不足而草率結尾或中途截斷。`,
    `16. 講義範圍邊界：本講義只完整說明子主題菜單中「${topicRef}」的『專屬核心概念』。凡是菜單中歸屬於其他子主題的概念（包括「跨子主題共用概念歸屬」表中歸屬他處的概念），即使本講義需要用到，也只能用一句話帶過其意思，並註明「詳見〈該子主題名稱〉講義」，不得重新定義、展開機制或舉例。若此對話中先前已撰寫過其他子主題的講義，那些講義已完整說明的內容同樣只能引用、不得重講。若某概念不在菜單任何子主題中，先在${LIMITS}列出請教師決定歸屬，不要自行展開。`
  ];
}

function handoutBody(topicRef, wordLine, opts) {
  const o = { ...HANDOUT_DEFAULTS, ...opts };
  const secs = handoutSections(o);
  const core = secs.find(s => s.key === "core").heading;
  return [
    "你是一位專攻管理學、行銷管理、消費者行為與行銷研究方法的大學教材作者，同時是研究方法嚴謹的課程設計者。",
    "",
    `任務：僅根據此 Notebook 中已提供的教科書章節、授課投影片、學術論文與案例，為「${topicRef}」撰寫一份供學生課前或課後閱讀的完整中文教學講義。動筆前請先在內部自行規劃概念順序與必教內容，但不要把規劃過程輸出，直接輸出講義本文。`,
    "",
    `講義總字數上限：${wordLine}`,
    "",
    ...handoutRules(topicRef, o, core),
    "",
    "請只輸出下列各節，不得自行增加其他章節（例如學習目標、重點整合表、自我檢核題）：",
    "",
    "# [單元標題]",
    ...secs.flatMap(s => ["", `## ${s.heading}`, ...s.body])
  ].join("\n");
}
