// ── [0] 教學主題菜單 ──
function build0() {
  const docs = $("m0_docs").value.split(/\n/).map(s => s.trim()).filter(Boolean);
  const topic = v("m0_topic");
  const max = parseInt(v("m0_max"), 10);
  const words = parseInt(v("m0_words"), 10) || 6000;

  const primaryLine = docs.length ? docs.join("、") : "此 Notebook 中已上傳的全部來源";
  const topicInstr = blank(topic)
    ? "我沒有指定大主題，請你先讀過上方範圍內的文獻內容，自行歸納一個能涵蓋這些文獻的教學大主題名稱，再以此為標題展開下面的任務。"
    : `教學大主題：${topic}`;

  const rules = [
    "只根據上方「文獻範圍」內的文獻內容列出候選子主題；若指定了特定文獻，Notebook 中其餘未列入範圍的文獻一律不得作為子主題的依據來源。",
    "不得憑常識補充這些文獻中沒有的子主題。",
    "每個候選子主題必須有至少一個可辨識的來源（文獻篇名／章節），並標示來源。",
    "若同一子主題有多個來源，合併為一項並列出所有來源。",
    `不要把「太細的小節」和「太大的整章」混在同一層級；每個候選項應大致對應一份約 ${words} 字講義可完整說明的份量。`,
    "標示每個子主題目前的資料完整度（充足／部分／薄弱），讓教師判斷是否值得單獨開一份講義。",
    "標示子主題之間的先後關係（若 A 需要先懂 B，註明）。",
    "不得替教師做「該教或不該教」的決定；只提供資訊協助判斷。",
    "子主題之間必須彼此互斥：每份講義日後會各自獨立撰寫，教師要求講義之間的內容重複降到極低。因此每一個核心概念、理論、模型或研究發現，只能歸屬於一個子主題，由該子主題的講義負責完整說明；不得讓兩個子主題的『專屬核心概念』出現同一個概念，也不得用換個名稱的方式切出實質內容重疊的兩個子主題。",
    "若某概念被多個子主題用到（例如共同的基礎定義），仍只能指定一個子主題為其歸屬（通常是最先教、或最以該概念為核心的那一個），其他子主題只能把它列為「先備子主題」引用，不得重新展開。",
    "輸出前請自行檢查：逐一比對各子主題的專屬核心概念，確認沒有任何概念同時出現在兩個子主題中；若發現重疊，調整切分方式後再輸出。"
  ];
  const topicOnly = !docs.length && !blank(topic);
  if (topicOnly) {
    rules.push(`只列出屬於「${topic}」範圍內的子主題；Notebook 中與此大主題無關的來源一律不得作為子主題依據，也不得為了扣上大主題而把無關內容硬套進來。`);
  }
  if (max > 0) {
    rules.push(`子主題總數不得超過 ${max} 個。若範圍內文獻的內容超過 ${max} 份講義能涵蓋的份量，請優先保留最核心、資料最充足的內容，其餘列入「範圍內涵蓋但可能不適合單獨開講義的內容」並說明理由，不得為了塞進更多內容而讓單一子主題超過一份 ${words} 字講義能完整說明的份量。`);
  }

  return [
    "你是一位行銷管理與研究方法領域的大學課程設計顧問。",
    "",
    "任務：僅根據下方指定範圍內的文獻，列出所有可獨立成一份學生講義的候選子主題，供授課教師勾選要教或不教，而不是直接寫講義內容。",
    "",
    "使用情境：",
    `- 文獻範圍：${primaryLine}`,
    `- ${topicInstr}`,
    "",
    "規則：",
    ...rules.map((r, i) => `${i + 1}. ${r}`),
    "",
    "請輸出：",
    "",
    "# [依上方大主題或你歸納出的主題名稱] 可教授子主題菜單",
    "",
    "## 建議教學順序總覽",
    "用一段話說明子主題之間大致的邏輯順序（不代表必須照此順序教）。",
    "",
    "## 子主題清單",
    "| # | 子主題名稱 | 一句話說明這在教什麼 | 專屬核心概念（只在此講義完整說明） | 對應來源 | 資料完整度 | 先備子主題 |",
    "|---|---|---|---|---|---|---|",
    "",
    "## 跨子主題共用概念歸屬",
    "列出會被兩個以上子主題用到的概念，指定唯一的歸屬子主題：",
    "| 概念 | 歸屬子主題（完整說明處） | 其他會用到的子主題（只引用、不重講） |",
    "|---|---|---|",
    "",
    "## 範圍內涵蓋但可能不適合單獨開講義的內容",
    "列出指定範圍文獻中有涉及、但太細碎或太邊緣，建議併入其他子主題而非獨立成講義的內容，並說明理由。",
    "",
    "## 講義邊界速查（供複製）",
    "把上面兩張表濃縮成純文字，整段放在一個程式碼區塊（```text 開頭、``` 結尾）中，方便教師一次選取複製到新對話。格式固定如下，一個子主題一行、一個共用概念一行，不得使用表格、條列符號或粗體：",
    "```text",
    "子主題 1｜[子主題名稱]｜專屬：[概念A]、[概念B]｜先備：[無或子主題編號]",
    "子主題 2｜[子主題名稱]｜專屬：[概念C]、[概念D]｜先備：子主題 1",
    "共用｜[概念名稱]｜歸屬：子主題 1｜引用：子主題 2、子主題 3",
    "```",
    "",
    ...(topicOnly ? [
      "## 來源採用核對",
      "列出 Notebook 中所有來源，分成兩類：「本次實際採用的來源」與「判定與大主題無關而未採用的來源」（後者每份用一句話說明判定理由），供教師核對。",
      ""
    ] : []),
    "## 待你勾選",
    "請回覆想教授的子主題編號，我會針對這些子主題各自撰寫講義。"
  ].join("\n");
}

function note0() {
  const words = parseInt(v("m0_words"), 10) || 6000;
  const msgs = [];
  if (words > 6000) msgs.push(`每份 ${words} 字已超過 NotebookLM 單次輸出約 6000 字的實際上限，講義後段可能被截斷。`);
  $("m0_note").className = "note" + (msgs.length ? " warn" : "");
  $("m0_note").textContent = msgs.length ? msgs.join(" ")
    : "小提醒：子主題切太多，每份講義會很薄；切太少，單份會超過 6000 字寫不完。上限可先設 4–6 個試試。";
}

MODULES["0"] = {
  build: build0, note: note0,
  next: "下一步：貼到已上傳教材的 NotebookLM 新對話 → 從回覆選定『一個』子主題 → 切到「講義生成」，在同一個對話接續貼上。"
};
