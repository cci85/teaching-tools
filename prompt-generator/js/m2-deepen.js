// ── [2] 深化既有段落：把講義中某個 ### 區塊改寫得更深入，輸出可直接替換的版本 ──
const DEEPEN_DIRS = {
  mech: ["機制與理論依據", "說明此概念「為什麼會這樣運作」，包括背後的理論假設、因果邏輯，以及它是為了解決前一個概念的什麼限制而提出。"],
  evid: ["實證研究", "補入來源中支持或檢驗此概念的實證研究，逐一說明研究問題、設計、主要變數、結果、可作出的推論與限制。"],
  comp: ["與相近概念比較", "說明此概念與相近概念的共同點、差異、適用範圍與常見誤解；相近概念若屬其他子主題，只能一句帶過並註明「詳見〈該子主題名稱〉講義」。"],
  exam: ["說明性例子", "再加 1 個明確標示為「說明性例子」的例子，情境不得與講義中其他例子重複；不得將例子當成來源已證實的實證結論。"],
  limi: ["限制與學術爭議", "說明此概念的適用邊界、來源之間的定義衝突或學術爭議；不可自行統一，須標示「資料界限」或「學術爭議」。"]
};

function deepenDirs() {
  return [...document.querySelectorAll('input[name="dp_dir"]:checked')].map(el => el.value);
}

function build2() {
  const text = $("dp_text").value.trim();
  if (!text) return "";
  const dirs = deepenDirs();
  const w = v("dp_words").replace(/\s*字$/, "");
  const lenLine = blank(w) ? "改寫後篇幅約為原段落的兩倍" : `改寫後篇幅約 ${w} 字`;
  const dirLines = dirs.length
    ? dirs.map((k, i) => `  ${String.fromCharCode(97 + i)}. ${DEEPEN_DIRS[k][0]}：${DEEPEN_DIRS[k][1]}`)
    : ["  未指定方向：請先判斷原段落最薄弱之處（例如機制交代不清、缺少實證、與相近概念的區別不明），自行選擇 1–2 個方向深化，並在「修改說明」中說明選擇理由。"];
  const extra = v("dp_extra");
  return [
    "你剛才在講義中寫了下面這一段（以下稱「原段落」）：",
    "",
    "<<<",
    text,
    ">>>",
    "",
    "任務：把原段落改寫成更深入的版本，用來直接替換講義中的原段落。只處理這一段，不要重寫講義其他部分。",
    "",
    "深化方向：",
    ...dirLines,
    "",
    "規則：",
    "1. 僅使用此 Notebook 來源中的理論、定義、研究結果與案例；不得編造引用、研究發現、數字或作者主張。重要主張以 APA 格式（作者, 年份）標示，不寫章節或頁碼。",
    "2. 只加深原段落所討論的概念，不得引入原段落沒有的新核心概念；先前子主題菜單中歸屬其他子主題的概念，仍只能一句帶過並註明「詳見〈該子主題名稱〉講義」。",
    "3. 保留原段落的 ### 標題與既有正確內容，在此基礎上擴充與重組，而不是另起爐灶；若發現原段落有錯誤或與來源不符，直接修正，並在「修改說明」中指出。",
    "4. 新增內容須與原段落連成一條連貫論述：先交代新內容與原有論點的關係，再展開，不得把新內容寫成接在後面的獨立補充。",
    "5. 沿用原段落的格式：原段落若是「標題 → 條列要點 → 段落文字」，改寫後也採此格式（條列 2–4 項，條列之後一定接段落論述）；原段落若是純段落，維持純段落。",
    "6. 若來源資料不足以支撐某個深化方向，直接說明該方向「資料界限」，不得憑常識硬補。",
    "7. 用繁體中文、正式教科書式論述；用詞一律使用「變數」，不得使用「變項」；不使用表格，不畫任何圖表或輸出圖表程式碼；不出現「教師可提問」等教案語言。",
    `8. ${lenLine}。`,
    "",
    "請輸出：",
    "",
    "### [沿用原段落標題]",
    "（改寫後的完整段落，可直接整段替換原段落）",
    "",
    "---",
    "",
    "## 修改說明",
    "以 2–5 點說明：新增了哪些內容及其依據來源、修正了原段落哪些地方、哪些深化方向因資料不足未能展開；若改寫後與講義其他段落出現重複，指出應刪減或改為指回的位置。"
  ].join("\n") + (blank(extra) ? "" : `\n\n教師補充要求：${extra}`);
}

function note2() {
  const text = $("dp_text").value.trim();
  const msgs = [];
  if (text && !/^#{2,4}\s/m.test(text)) msgs.push("貼上的內容沒有 ### 標題；建議連同該段標題一起貼，AI 才能準確對應講義位置。");
  if (text.length > 2500) msgs.push("貼上的段落很長，建議一次只深化一個 ### 區塊。");
  $("dp_note").className = "note" + (msgs.length ? " warn" : "");
  $("dp_note").textContent = msgs.join(" ");
}

MODULES["2"] = {
  build: build2, note: note2,
  empty: "（請先貼上要深化的講義段落）",
  next: "下一步：回到寫出這份講義的同一個 NotebookLM 對話貼上（不要開新對話），再用輸出的段落替換講義原段落。"
};
