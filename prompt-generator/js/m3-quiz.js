function build3() {
  const line = (id, def) => blank(v(id)) ? def : `${v(id)} 題`;
  return [
    "接續你剛才生成的學生講義，請設計個人測驗題。",
    "",
    "任務：僅根據這份講義與此 Notebook 中的來源內容，依序出下列三種題型（題數為 0 的題型整段略過不輸出）：",
    `- 第一部分：四選一單選題 ${line("m3_mc", "8 到 10 題")}`,
    `- 第二部分：簡答／申論題 ${line("m3_sa", "3 到 5 題")}`,
    `- 第三部分：情境應用題 ${line("m3_case", "1 到 2 題")}`,
    "",
    "共同規則：",
    "1. 題目必須涵蓋講義中不同章節的概念，不要集中在同一節；三個部分之間避免考同一個知識點。",
    "2. 不得出「講義沒有明確提到」的內容；每題都要能在講義或來源中找到依據，並標示對應講義章節。",
    "",
    "第一部分（選擇題）規則：",
    "1. 由基礎定義到應用理解都要有。",
    "2. 每題只能有一個最佳答案；其餘三個選項須是常見誤解或似是而非的錯誤說法，不得是明顯不合理的干擾選項。",
    "3. 每題附上正確答案，以及『每一個選項』為何正確或錯誤的簡短理由（1-2 句），而不是只解釋正確答案。",
    "",
    "第二部分（簡答／申論題）規則：",
    "1. 題目須要求學生解釋概念、比較概念間差異、說明理論機制，或評估某個主張的合理性，不得只是「請定義 XX」這種可以照抄講義的題目。",
    "2. 參考答案以『評分要點』呈現而非唯一標準答案，允許學生用不同措辭表達相同理解；評分要點須列出必要論點（缺一不可）、加分項目（例如舉出例子、指出限制），以及常見錯誤或混淆之處。",
    "3. 每題標示所評量的認知層次（記憶理解／分析比較／評估應用）。",
    "",
    "第三部分（情境應用題）規則：",
    "1. 每題描述一個具體的管理或行銷情境（可為虛構但合理的公司、產品或決策場景，3-6 句），並給出作答要求（例如「請指出本情境中適用的理論，並說明其如何解釋此現象／可如何介入」）。",
    "2. 情境可以是教學設計出來的案例，但要求學生應用的『理論與概念』必須來自講義與來源，不得要求學生用講義未涵蓋的理論作答。",
    "3. 評分要點須列出：應辨識的關鍵理論或概念、合理的分析路徑（1-2 種）、常見的誤用或過度簡化的分析方式；允許多元解法，但須說明什麼樣的分析才算『有理論根據』而非憑直覺作答。",
    "",
    "請輸出：",
    "",
    "# 個人測驗題",
    "",
    "## 第一部分：選擇題",
    "對每一題依序輸出：",
    "第 N 題：題目",
    "(A)...(B)...(C)...(D)...",
    "正確答案：",
    "選項解析：逐一說明 A/B/C/D 各自為何正確或錯誤",
    "對應講義章節：",
    "",
    "## 第二部分：簡答／申論題",
    "對每一題依序輸出：",
    "第 N 題：題目",
    "認知層次：",
    "評分要點：",
    "  - 必要論點：",
    "  - 加分項目：",
    "  - 常見錯誤／混淆：",
    "對應講義章節：",
    "",
    "## 第三部分：情境應用題",
    "對每一題依序輸出：",
    "第 N 題：",
    "情境描述：",
    "作答要求：",
    "評分要點：",
    "  - 應辨識的理論／概念：",
    "  - 合理分析路徑：",
    "  - 常見誤用：",
    "對應講義章節：",
    ""
  ].join("\n");
}

function note3() {
  const n = id => blank(v(id)) ? null : parseInt(v(id), 10);
  const all = ["m3_mc", "m3_sa", "m3_case"].map(n);
  $("m3_note").className = "note warn";
  $("m3_note").textContent = all.every(x => x === 0) ? "三種題型都填 0，這樣不會出任何題目。" : "";
}

MODULES["3"] = { build: build3, note: note3, next: "下一步：回到同一個 NotebookLM 對話貼上（不要開新對話）。" };
