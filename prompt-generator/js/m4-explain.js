// ── [4] 白話解釋句子 ──
function build4() {
  const s = $("m4_s").value.trim();
  if (!s) return "";
  return [
    "你剛才在講義中寫了這句話：",
    "",
    `「${s}」`,
    "",
    "請用白話文重新解釋這句話在說什麼，具體回答：",
    "1. 這句話想表達的核心意思是什麼？請用一般大學生能懂的語言重寫一次，不要用更多學術術語堆疊。",
    "2. 句中出現的專業或抽象詞彙分別指涉什麼？請對照你依據的來源原文，說明這些詞是你自己的措辭，還是來源文獻本身就這樣寫。",
    "3. 這句話跟前後文的論述關係是什麼（它在支持、補充，還是對比前面提到的概念）？",
    "",
    "如果這句話是你自己為了呈現學術語感而寫的修辭句，且沒有明確對應到來源中的具體論述，請直接說明「此句為教學性總結，非直接引自來源」，不要硬掰一個來源出處。",
    "",
    "最後，請直接給我一句可以取代原句、意思相同但更白話的版本，方便我直接拿去替換講義中的原句。"
  ].join("\n");
}

MODULES["4"] = {
  build: build4, empty: "（請先貼上看不懂的句子）",
  next: "下一步：回到同一個 NotebookLM 對話貼上（不要開新對話）。"
};
